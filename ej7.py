def main():
    num1 = float(input("Introduce el primer número a sumar: "))
    num2 = float(input("Introduce el segundo número a sumar: "))
    num3 = float(input("Introduce el tercer número a sumar: "))
    
    resultado = num1 + num2 + num3 
    print(f"El número resultado de la suma de los 3 introducidos será de: {resultado}")
if __name__ == "__main__":
    main()